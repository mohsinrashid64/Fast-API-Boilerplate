"""Render and write the files for a new table (model, schemas, CRUD, routes,
migration, tests). New files only: existing files are never modified."""

from datetime import datetime
from pathlib import Path
from typing import Any

from alembic.config import Config
from alembic.script import ScriptDirectory
from jinja2 import Environment, FileSystemLoader, StrictUndefined

from app.codegen.spec import Resolved, TableSpec, py_literal, resolve
from app.core.config import PROJECT_ROOT

_env = Environment(
    loader=FileSystemLoader(Path(__file__).parent / "templates"),
    undefined=StrictUndefined,
    trim_blocks=True,
    lstrip_blocks=True,
    keep_trailing_newline=True,
    autoescape=False,  # generates Python, not HTML; all values are validated identifiers or repr()s
)
_env.filters["pyrepr"] = py_literal


class GenerationError(RuntimeError):
    pass


def _header(table: str) -> str:
    return (
        f'"""Generated by the admin table builder for the `{table}` table '
        f"on {datetime.now():%Y-%m-%d}.\n\nIt's ordinary code now: edit it freely.\n\"\"\""
    )


def _next_revision(root: Path) -> tuple[str, str | None]:
    cfg = Config(str(root / "alembic.ini"))
    cfg.set_main_option("script_location", str(root / "alembic"))
    script = ScriptDirectory.from_config(cfg)
    heads = script.get_heads()
    if len(heads) > 1:
        raise GenerationError(f"Alembic has several heads ({', '.join(heads)}); merge them first.")
    numbers = [int(rev.revision) for rev in script.walk_revisions() if rev.revision.isdigit()]
    return f"{max(numbers, default=0) + 1:04d}", (heads[0] if heads else None)


def render_files(spec: TableSpec, root: Path = PROJECT_ROOT) -> tuple[Resolved, dict[str, str]]:
    """Validate the spec and render every file. Returns (resolved spec, {relative path: source}).

    Raises SpecError for invalid input, GenerationError if rendering produced invalid Python.
    """
    r = resolve(spec, root)
    revision, down = _next_revision(root)
    header = _header(r.table_name)
    update_col = next((c for c in r.columns if c.type in ("string", "text", "integer", "big_integer", "boolean")), None)
    ctx: dict[str, Any] = {"r": r, "header": header, "update_col": update_col}

    files = {
        f"app/models/{r.module}.py": _env.get_template("model.py.j2").render(ctx),
        f"app/schemas/{r.module}.py": _env.get_template("schema.py.j2").render(ctx),
        f"app/crud/{r.module}_crud.py": _env.get_template("crud.py.j2").render(ctx),
        f"app/routes/{r.module}.py": _env.get_template("router.py.j2").render(ctx),
        f"alembic/versions/{revision}_create_{r.table_name}.py": _env.get_template("migration.py.j2").render(
            {**ctx, "revision": revision, "down_revision": down, "now": f"{datetime.now():%Y-%m-%d %H:%M:%S}"}
        ),
    }
    if r.generate_tests:
        files[f"tests/test_{r.module}_api.py"] = _env.get_template("test.py.j2").render(ctx)

    for path, source in files.items():
        try:
            compile(source, path, "exec")
        except SyntaxError as exc:  # a bug in a template, never user input
            raise GenerationError(f"Generated {path} is not valid Python: {exc}") from exc
    return r, files


def write_files(files: dict[str, str], root: Path = PROJECT_ROOT) -> list[str]:
    """Create the files (all or nothing). Refuses to overwrite anything."""
    targets = {root / rel: source for rel, source in files.items()}
    existing = [str(p.relative_to(root)) for p in targets if p.exists()]
    if existing:
        raise GenerationError(f"Refusing to overwrite existing files: {', '.join(existing)}")

    written: list[Path] = []
    try:
        for path, source in targets.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "x", encoding="utf-8") as fh:  # "x" = fail if it appeared meanwhile
                fh.write(source)
            written.append(path)
    except Exception as exc:
        for path in written:
            path.unlink(missing_ok=True)
        raise GenerationError(f"Could not write the files: {exc}") from exc
    return [str(p.relative_to(root)) for p in written]


async def create_table(spec: TableSpec, apply: bool = True, root: Path = PROJECT_ROOT) -> dict[str, Any]:
    """Generate the files, then (optionally) apply the new migration to the active database."""
    from app.core.db_admin import DatabaseConfigError, migrate_to_head
    from app.database import active_database_url

    r, files = render_files(spec, root)
    created = write_files(files, root)
    migration = next(p for p in created if p.startswith("alembic/versions/"))

    result: dict[str, Any] = {
        "table": r.table_name,
        "model": r.class_name,
        "api_path": f"/{r.url}",
        "files": created,
        "migration": migration,
        "applied": False,
        "apply_error": None,
    }
    if apply:
        try:
            status = await migrate_to_head(active_database_url())
            result["applied"] = status["up_to_date"]
        except DatabaseConfigError as exc:
            # Files stay: the migration can be applied later from the Database page.
            result["apply_error"] = str(exc)
    return result
