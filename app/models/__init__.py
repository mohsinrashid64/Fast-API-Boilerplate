"""All SQLAlchemy models.

Every module in this package is imported automatically, so a new model file
(hand-written or generated by the admin table builder) is registered on
`Base.metadata` without editing this file. The explicit imports below are kept
for editors and type checkers.
"""

import importlib
import pkgutil

from app.database.db_config import Base

from .otp import OTP
from .product import Product
from .reset_token import ResetToken
from .user import User
from .user_auth import UserAuth

for _module in pkgutil.iter_modules(__path__):
    importlib.import_module(f"{__name__}.{_module.name}")

# Re-export every mapped model, e.g. `from app.models import Category`.
for _mapper in Base.registry.mappers:
    globals().setdefault(_mapper.class_.__name__, _mapper.class_)

__all__ = sorted(m.class_.__name__ for m in Base.registry.mappers)
