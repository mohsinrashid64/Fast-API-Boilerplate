"""All API routers.

The core routers are included first (in this order); then every other module in
this package that defines `router` is included automatically, so new route files
(hand-written or generated by the admin table builder) need no registration.
"""

import importlib
import pkgutil

from fastapi import APIRouter

CORE_MODULES = ["auth", "user", "otp", "product"]

router = APIRouter()

_others = sorted(m.name for m in pkgutil.iter_modules(__path__) if m.name not in CORE_MODULES)
for _name in CORE_MODULES + _others:
    _module = importlib.import_module(f"{__name__}.{_name}")
    if isinstance(getattr(_module, "router", None), APIRouter):
        router.include_router(_module.router)
